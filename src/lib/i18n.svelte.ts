const dicts = { ru, en };

export const i18n = $state({ lang: "ru" as "ru" | "en" });

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = dicts[i18n.lang][key] ?? ru[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function ago(ts: number): string {
  const d = Date.now() - ts;
  if (d < 60_000) return t("time.now");
  if (d < 3_600_000) return t("time.min", { n: Math.floor(d / 60_000) });
  if (d < 86_400_000) return t("time.hour", { n: Math.floor(d / 3_600_000) });
  if (d < 2 * 86_400_000) return t("time.yesterday");
  return new Date(ts).toLocaleDateString(i18n.lang === "ru" ? "ru-RU" : "en-GB", { day: "numeric", month: "short" });
}
